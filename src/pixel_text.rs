/// Columns of `c`; anything outside printable ASCII shows as `?`.
fn glyph(c: char) -> [u8; 5] {
    let i = (c as usize).wrapping_sub(0x20);
    FONT.get(i).copied().unwrap_or(FONT[b'?' as usize - 0x20])
}

/// `label` in bright dots, then `path` in muted ones, with a band of light
/// crossing the row. Fills the width it's given and cuts the path to fit.
/// `time` is the card's clock in seconds.
pub fn status(label: &'static str, path: String, time: f32, muted: u32) -> impl IntoElement {
    canvas(
        |_, _, _| {},
        move |bounds, _, window, _| paint(label, &path, time, muted, bounds, window),
    )
    .flex_1()
    .min_w_0()
    .h(px(ROWS as f32 * CELL))
}

fn paint(
    label: &str,
    path: &str,
    time: f32,
    muted: u32,
    bounds: Bounds<Pixels>,
    window: &mut Window,
) {
    let fits = (f32::from(bounds.size.width) / CELL) as usize;
    let dot = px(0.75);
    // The band crosses the whole row at one speed, so long paths don't make
    // it rush, then waits off the end a moment before the next pass.
    let span = fits as f32 + 60.0;
    let sweep = (time * SPEED) % span - 20.0;
    // Dots flicker on a coarser clock than the frame rate, like film grain.
    let frame = (time * 12.0) as i32;

    let path_at = label.len() * ADVANCE + GAP;
    let room = fits.saturating_sub(path_at) / ADVANCE;
    let path: String = if path.chars().count() > room {
        let keep = room.saturating_sub(3);
        path.chars().take(keep).chain("...".chars()).collect()
    } else {
        path.into()
    };

    let mut draw = |text: &str, start: usize, color: Rgba| {
        for (i, c) in text.chars().enumerate() {
            for (col, bits) in glyph(c).into_iter().enumerate() {
                let x = start + i * ADVANCE + col;
                if x >= fits {
                    return;
                }
                for row in 0..ROWS {
                    if bits & (1 << row) == 0 {
                        continue;
                    }
                    let (x, y) = (x as i32, row as i32);
                    let near = (-((x as f32 - sweep) / 10.0).powi(2)).exp();
                    let mut light = 0.75 + 0.25 * near;
                    if hash01(x + frame * 131, y + frame * 71) < 0.12 {
                        light *= 0.45;
                    }
                    // Muted text brightens toward white as the band passes.
                    let mix = |a: u8| (a as f32 + (255.0 - a as f32) * near * 0.6) as u8;
                    let lit = Rgba {
                        r: mix(color.r),
                        g: mix(color.g),
                        b: mix(color.b),
                        a: (light * 255.0) as u8,
                    };
                    let at = point(
                        bounds.origin.x + px(x as f32 * CELL),
                        bounds.origin.y + px(y as f32 * CELL),
                    );
                    window.paint_quad(fill(Bounds::new(at, size(dot, dot)), hsla(lit)));
                }
            }
        }
    };
    draw(label, 0, Rgba::WHITE);
    // Sparse dots read darker than solid text of the same color.
    let muted = Rgba::hex(muted);
    let lift = |c: u8| c + ((255 - c) as f32 * 0.35) as u8;
    let muted = Rgba {
        r: lift(muted.r),
        g: lift(muted.g),
        b: lift(muted.b),
        ..muted
    };
    draw(&path, path_at, muted);
}
